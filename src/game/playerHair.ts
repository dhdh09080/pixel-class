export function playerHair(
  p: PixelArt,
  a: Required<Appearance>,
  back: boolean,
  front: boolean,
  bob: number,
) {
  const base = a.hair,
    dark = shade(base, '#171827', 0.42),
    light = shade(base, '#ddd7dd', 0.3),
    shine = shade(base, '#fff3d0', 0.5),
    ink = '#262333';
  const offset = (pts: readonly PixelPoint[]) => pts.map(([x, y]) => [x, y + bob] as PixelPoint);
  if (front) {
    if (back) return;
    p.layer((q) => {
      q.poly(offset(fringes[a.hairstyle] || fringes[0]), base);
      q.poly(
        offset([
          [16, 27],
          [20, 22],
          [29, 20],
          [37, 22],
          [40, 25],
          [35, 25],
          [30, 23],
          [22, 24],
          [19, 28],
        ]),
        light,
      );
      q.rect(22, 23 + bob, 7, 1, shine);
      q.poly(
        offset([
          [41, 27],
          [45, 30],
          [45, 39],
          [42, 38],
        ]),
        dark,
      );
      if (a.hairstyle === 14) {
        q.rect(20, 29 + bob, 2, 1, dark);
        q.rect(29, 26 + bob, 2, 1, dark);
        q.rect(38, 30 + bob, 2, 1, dark);
      }
    });
    return;
  }
  p.layer((q) => {
    if ([1, 3, 7, 10, 11, 15, 17].includes(a.hairstyle)) {
      const end = [3, 11].includes(a.hairstyle) ? 58 : 73;
      q.poly(
        offset([
          [15, 27],
          [11, 35],
          [11, 49],
          [9, end - 4],
          [13, end],
          [19, end - 1],
          [22, end - 6],
          [38, end - 6],
          [42, end],
          [48, end - 1],
          [51, end - 5],
          [48, 46],
          [48, 30],
          [40, 20],
          [24, 19],
        ]),
        dark,
      );
      q.poly(
        offset([
          [15, 32],
          [14, 48],
          [12, end - 5],
          [17, end - 2],
          [20, end - 9],
          [20, 35],
        ]),
        base,
      );
      q.poly(
        offset([
          [40, 31],
          [41, 49],
          [44, end - 3],
          [49, end - 4],
          [45, 46],
          [45, 31],
        ]),
        base,
      );
      q.line(
        offset([
          [15, 39],
          [15, 52],
          [13, end - 6],
        ]),
        light,
      );
      q.line(
        offset([
          [45, 38],
          [45, 53],
          [47, end - 7],
        ]),
        light,
      );
      if (a.hairstyle === 7 || a.hairstyle === 15) {
        q.poly(
          offset([
            [11, 51],
            [9, 57],
            [11, 62],
            [10, 68],
            [14, 72],
            [16, 69],
            [13, 63],
            [14, 58],
          ]),
          base,
        );
        q.poly(
          offset([
            [47, 48],
            [51, 55],
            [49, 60],
            [52, 66],
            [48, 73],
            [45, 71],
            [48, 65],
            [45, 59],
          ]),
          base,
        );
      }
    }
    if (a.hairstyle === 4 || a.hairstyle === 10) {
      q.poly(
        offset([
          [40, 20],
          [49, 20],
          [53, 25],
          [53, 41],
          [51, 51],
          [55, 66],
          [52, 74],
          [48, 77],
          [49, 67],
          [45, 55],
          [46, 39],
          [43, 28],
        ]),
        base,
      );
      q.poly(
        offset([
          [48, 26],
          [50, 28],
          [50, 44],
          [48, 54],
          [52, 68],
          [50, 72],
          [48, 63],
          [46, 52],
        ]),
        light,
      );
    }
    if (a.hairstyle === 12) {
      q.oval(23, 45 + bob, 17, 12, base);
      q.rect(25, 48 + bob, 10, 2, light);
    }
    if (a.hairstyle === 5) {
      for (const x of [7, 43]) {
        q.oval(x, 21 + bob, 11, 12, base);
        q.rect(x + 2, 23 + bob, 6, 2, light);
      }
    }
    if (a.hairstyle === 8 || a.hairstyle === 16) {
      for (const x of [11, 43]) {
        for (let y = 40; y < 70; y += 5) {
          q.poly(
            offset([
              [x + 2, y],
              [x + 6, y + 1],
              [x + 7, y + 4],
              [x + 4, y + 7],
              [x, y + 4],
            ]),
            base,
          );
          q.rect(x + 2, y + 2 + bob, 2, 2, light);
        }
        q.rect(x, 69 + bob, 7, 2, a.accentColor);
      }
    }
    q.poly(offset(crown), base);
    q.poly(
      offset([
        [42, 25],
        [46, 29],
        [47, 38],
        [42, 43],
        [38, 43],
        [41, 36],
      ]),
      dark,
    );
    if (back) {
      q.poly(
        offset([
          [18, 25],
          [24, 21],
          [34, 21],
          [40, 24],
          [37, 26],
          [26, 24],
          [20, 27],
        ]),
        light,
      );
      for (const x of [18, 25, 36, 43])
        q.line(
          offset([
            [x, 31],
            [x + 1, 40],
            [x, 47],
          ]),
          dark,
        );
      if ([1, 7, 10, 15, 17].includes(a.hairstyle))
        q.poly(
          offset([
            [17, 43],
            [17, 62],
            [20, 68],
            [40, 68],
            [44, 60],
            [44, 41],
          ]),
          base,
        );
    }
  });
  // Hair ornaments are part of the hairstyle layer and hidden under occupational hats.
  if ((a.hairstyle === 10 || a.hairstyle === 5) && a.helmetStyle === 1)
    p.layer((q) => {
      for (const [cx, cy] of a.hairstyle === 10
        ? [[33, 17]]
        : [
            [13, 29],
            [48, 29],
          ]) {
        q.poly(
          offset([
            [cx - 1, cy],
            [cx - 9, cy - 5],
            [cx - 10, cy + 1],
            [cx - 6, cy + 5],
            [cx, cy + 2],
            [cx + 7, cy + 6],
            [cx + 11, cy + 1],
            [cx + 9, cy - 4],
            [cx + 2, cy],
          ]),
          a.hairstyle === 10 ? base : a.accentColor,
        );
        q.rect(cx - 7, cy - 2 + bob, 4, 1, light);
        q.rect(cx, cy + bob, 2, 3, ink);
      }
    });
}
